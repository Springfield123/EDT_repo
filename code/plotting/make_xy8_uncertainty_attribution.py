#!/usr/bin/env python3
"""Attribute XY8 control uncertainty to measurable hardware resources.

The analysis reuses the deterministic Monte Carlo sample set generated by
``make_xy8_extended_analyses.py``.  It reports four complementary views:

* one-at-a-time control sweeps around the nominal calibration;
* bootstrapped Spearman rank correlations with decision outcomes;
* cross-validated permutation importance for predicting the optimal depth;
* the decision value of measuring one resource while leaving the others at
  their nominal values.

The last quantity is the primary presentation metric.  For each Monte Carlo
case, the model selects a control after revealing only one resource group, and
that control is evaluated against the full (hidden) hardware condition.
"""

