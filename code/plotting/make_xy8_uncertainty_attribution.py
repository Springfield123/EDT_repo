def write_rows(path: Path, rows: list[dict]) -> None:
    if not rows:
        raise ValueError(f"Cannot write an empty table to {path}")
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0].keys()))
        writer.writeheader()
        writer.writerows(rows)


def load_sample_rows(path: Path) -> list[dict]:
    with path.open("r", encoding="utf-8", newline="") as handle:
        raw_rows = list(csv.DictReader(handle))
    rows = []
    for raw in raw_rows:
        rows.append(
            {
                "sample_id": int(raw["sample_id"]),
                **{column: float(raw[column]) for column in INPUT_COLUMNS},
            }
        )
    if not rows:
        raise ValueError(f"No Monte Carlo samples found in {path}")
    return rows


def calibration_for_sample(nominal: dict, row: dict) -> dict:
    calibration = deepcopy(nominal)
    calibration["label"] = f"nominal_mc_{int(row['sample_id']):04d}"
    calibration["pulse"]["piPulseFid"] = float(row["piPulseFid"])
    calibration["coherence"]["T2_1"] = float(nominal["coherence"]["T2_1"] * row["T2_scale"])
    calibration["coherence"]["alpha"] = float(row["T2_alpha"])
    calibration["readout"]["C_1"] = float(nominal["readout"]["C_1"] * row["contrast_scale"])
    calibration["readout"]["effective_detected_rate_cps"] = float(
        nominal["readout"]["effective_detected_rate_cps"] * row["photon_rate_scale"]
    )
    for key in ["t_init", "t_read", "t_dead"]:
        calibration["overheads"][key] = float(nominal["overheads"][key] * row["overhead_scale"])
    return calibration


def result_surface(results, taus, Ns) -> np.ndarray:
    values = {(float(tau), int(N)): float(eta) for tau, N, eta in results}
    return np.array([[values[(float(tau), int(N))] for tau in taus] for N in Ns], dtype=float)


def control_index(taus: np.ndarray, Ns: np.ndarray, tau: float, N: int) -> tuple[int, int]:
    n_matches = np.flatnonzero(Ns == int(N))
    if n_matches.size != 1:
        raise ValueError(f"Control depth N={N} is not represented exactly once.")
    tau_index = int(np.argmin(np.abs(taus - float(tau))))
    if not np.isclose(taus[tau_index], tau, rtol=0.0, atol=1e-15):
        raise ValueError(f"Control spacing tau={tau} is absent from the canonical grid.")
    return int(n_matches[0]), tau_index


def evaluate_existing_samples(nominal: dict, rows: list[dict], f_target: float):
    nominal_results, nominal_meta, _, _, reference_taus, reference_ns = sweep.evaluate_calibration(
        nominal, f_target=f_target
    )
    nominal_index = control_index(
        reference_taus,
        reference_ns,
        nominal_meta["tau_best"],
        nominal_meta["N_best"],
    )

    enriched_rows = []
    surfaces = []
    for row in rows:
        calibration = calibration_for_sample(nominal, row)
        results, meta, _, _, taus, Ns = sweep.evaluate_calibration(calibration, f_target=f_target)
        if not np.array_equal(taus, reference_taus) or not np.array_equal(Ns, reference_ns):
            raise RuntimeError("Uncertainty samples produced inconsistent control grids.")
        surface = result_surface(results, taus, Ns)
        surfaces.append(surface)
        best_eta = float(np.min(surface))
        fixed_regret = float(surface[nominal_index] / max(best_eta, 1e-30))
        window = meta["edt_window_10pct"]
        enriched_rows.append(
            {
                **row,
                "tau_best_s": float(meta["tau_best"]),
                "N_best": int(meta["N_best"]),
                "eta_best": float(meta["eta_best"]),
                "edt_window_N_min": int(window["N_min"]),
                "edt_window_N_max": int(window["N_max"]),
                "edt_window_width_blocks": int(window["N_max"] - window["N_min"]),
                "edt_window_touches_boundary": int(
                    window["touches_tau_boundary"] or window["touches_N_boundary"]
                ),
                "fixed_N20_penalty_pct": 100.0 * (fixed_regret - 1.0),
            }
        )
    return (
        enriched_rows,
        np.stack(surfaces),
        reference_taus,
        reference_ns,
        nominal_meta,
        nominal_results,
    )


def average_ranks(values: np.ndarray) -> np.ndarray:
    values = np.asarray(values, dtype=float)
    order = np.argsort(values, kind="mergesort")
    ranks = np.empty(values.size, dtype=float)
    start = 0
    while start < values.size:
        stop = start + 1
        while stop < values.size and values[order[stop]] == values[order[start]]:
            stop += 1
        ranks[order[start:stop]] = 0.5 * (start + stop - 1) + 1.0
        start = stop
    return ranks


def spearman_rho(x: np.ndarray, y: np.ndarray) -> float:
    rx = average_ranks(np.asarray(x, dtype=float))
    ry = average_ranks(np.asarray(y, dtype=float))
    if np.ptp(rx) == 0.0 or np.ptp(ry) == 0.0:
        return 0.0
    return float(np.corrcoef(rx, ry)[0, 1])


def bootstrap_interval(values: np.ndarray, statistic, samples: int, rng: np.random.Generator):
    values = np.asarray(values)
    estimates = np.empty(samples, dtype=float)
    for index in range(samples):
        selected = rng.integers(0, len(values), size=len(values))
        estimates[index] = float(statistic(selected))
    return float(np.quantile(estimates, 0.025)), float(np.quantile(estimates, 0.975))


def rank_correlations(rows: list[dict], bootstrap_samples: int, seed: int) -> list[dict]:
    rng = np.random.default_rng(seed)
    results = []
    for measurement in INPUT_COLUMNS:
        resource = next(name for name, columns in RESOURCE_GROUPS.items() if measurement in columns)
        x = np.array([row[measurement] for row in rows], dtype=float)
        for outcome in OUTCOME_LABELS:
            y = np.array([row[outcome] for row in rows], dtype=float)
            rho = spearman_rho(x, y)

            def statistic(indices):
                return spearman_rho(x[indices], y[indices])

            ci_low, ci_high = bootstrap_interval(
                np.arange(len(rows)), statistic, bootstrap_samples, rng
            )
            results.append(
                {
                    "resource": resource,
                    "resource_label": RESOURCE_LABELS[resource],
                    "measurement": measurement,
                    "measurement_label": MEASUREMENT_LABELS[measurement],
                    "outcome": outcome,
                    "outcome_label": OUTCOME_LABELS[outcome],
                    "spearman_rho": rho,
                    "abs_spearman_rho": abs(rho),
                    "bootstrap_95pct_lower": ci_low,
                    "bootstrap_95pct_upper": ci_high,
                    "bootstrap_samples": int(bootstrap_samples),
                }
            )
    return results


def _knn_predict(train_x: np.ndarray, train_y: np.ndarray, test_x: np.ndarray, neighbors: int) -> np.ndarray:
    mean = np.mean(train_x, axis=0)
    scale = np.std(train_x, axis=0)
    scale[scale < 1e-12] = 1.0
    train_z = (train_x - mean) / scale
    test_z = (test_x - mean) / scale
    distances = np.sum((test_z[:, None, :] - train_z[None, :, :]) ** 2, axis=2)
    k = min(max(int(neighbors), 1), train_x.shape[0])
    nearest = np.argpartition(distances, kth=k - 1, axis=1)[:, :k]
    return np.mean(train_y[nearest], axis=1)


def permutation_importance(
    rows: list[dict],
    repeats: int,
    seed: int,
    folds: int = 5,
    neighbors: int = 15,
) -> list[dict]:
    x = np.array([[row[column] for column in INPUT_COLUMNS] for row in rows], dtype=float)
    y = np.array([row["N_best"] for row in rows], dtype=float)
    rng = np.random.default_rng(seed)
    shuffled = rng.permutation(len(rows))
    fold_indices = np.array_split(shuffled, min(folds, len(rows)))

    baseline_predictions = np.empty(len(rows), dtype=float)
    fold_models = []
    for test_index in fold_indices:
        train_index = np.setdiff1d(np.arange(len(rows)), test_index, assume_unique=True)
        baseline_predictions[test_index] = _knn_predict(
            x[train_index], y[train_index], x[test_index], neighbors
        )
        fold_models.append((train_index, test_index))
    baseline_mae = float(np.mean(np.abs(baseline_predictions - y)))

    results = []
    for resource, measurements in RESOURCE_GROUPS.items():
        columns = [INPUT_COLUMNS.index(measurement) for measurement in measurements]
        increases = np.empty(repeats, dtype=float)
        for repeat in range(repeats):
            predictions = np.empty(len(rows), dtype=float)
            for train_index, test_index in fold_models:
                perturbed = x[test_index].copy()
                order = rng.permutation(len(test_index))
                perturbed[:, columns] = perturbed[order][:, columns]
                predictions[test_index] = _knn_predict(
                    x[train_index], y[train_index], perturbed, neighbors
                )
            increases[repeat] = float(np.mean(np.abs(predictions - y)) - baseline_mae)
        results.append(
            {
                "resource": resource,
                "resource_label": RESOURCE_LABELS[resource],
                "prediction_target": "N_best",
                "model": f"{folds}-fold cross-validated {neighbors}-nearest-neighbour regression",
                "baseline_mae_blocks": baseline_mae,
                "permutation_mae_increase_blocks": float(np.mean(increases)),
                "permutation_95pct_lower": float(np.quantile(increases, 0.025)),
                "permutation_95pct_upper": float(np.quantile(increases, 0.975)),
                "relative_mae_increase": float(np.mean(increases) / max(baseline_mae, 1e-30)),
                "permutation_repeats": int(repeats),
            }
        )
    return results


def apply_resource_measurement(nominal: dict, row: dict, resource: str) -> dict:
    calibration = deepcopy(nominal)
    calibration["label"] = f"single_measurement_{resource}_{int(row['sample_id']):04d}"
    if resource == "pulse_fidelity":
        calibration["pulse"]["piPulseFid"] = float(row["piPulseFid"])
    elif resource == "coherence":
        calibration["coherence"]["T2_1"] = float(nominal["coherence"]["T2_1"] * row["T2_scale"])
        calibration["coherence"]["alpha"] = float(row["T2_alpha"])
    elif resource == "optical_contrast":
        calibration["readout"]["C_1"] = float(nominal["readout"]["C_1"] * row["contrast_scale"])
    elif resource == "photon_rate":
        calibration["readout"]["effective_detected_rate_cps"] = float(
            nominal["readout"]["effective_detected_rate_cps"] * row["photon_rate_scale"]
        )
    elif resource == "timing_overhead":
        for key in ["t_init", "t_read", "t_dead"]:
            calibration["overheads"][key] = float(nominal["overheads"][key] * row["overhead_scale"])
    else:
        raise KeyError(resource)
    return calibration


def calibration_value(
    nominal: dict,
    rows: list[dict],
    surfaces: np.ndarray,
    taus: np.ndarray,
    Ns: np.ndarray,
    nominal_meta: dict,
    f_target: float,
    bootstrap_samples: int,
    seed: int,
):
    fixed_index = control_index(taus, Ns, nominal_meta["tau_best"], nominal_meta["N_best"])
    sample_best = np.min(surfaces, axis=(1, 2))
    fixed_regret = surfaces[:, fixed_index[0], fixed_index[1]] / np.maximum(sample_best, 1e-30)
    rng = np.random.default_rng(seed)
    summary_rows = []
    decision_rows = []

    for resource in RESOURCE_GROUPS:
        measured_regret = np.empty(len(rows), dtype=float)
        selected_depths = []
        selected_taus = []
        for index, row in enumerate(rows):
            calibration = apply_resource_measurement(nominal, row, resource)
            _, meta, _, _, candidate_taus, candidate_ns = sweep.evaluate_calibration(
                calibration, f_target=f_target
            )
            if not np.array_equal(candidate_taus, taus) or not np.array_equal(candidate_ns, Ns):
                raise RuntimeError("Single-resource calibration changed the canonical control grid.")
            selected = control_index(taus, Ns, meta["tau_best"], meta["N_best"])
            measured_regret[index] = float(
                surfaces[index, selected[0], selected[1]] / max(sample_best[index], 1e-30)
            )
            selected_depths.append(int(meta["N_best"]))
            selected_taus.append(float(meta["tau_best"]))
            decision_rows.append(
                {
                    "sample_id": int(row["sample_id"]),
                    "resource": resource,
                    "resource_label": RESOURCE_LABELS[resource],
                    "selected_tau_s": float(meta["tau_best"]),
                    "selected_N": int(meta["N_best"]),
                    "regret": float(measured_regret[index]),
                    "performance_penalty_pct": 100.0 * (float(measured_regret[index]) - 1.0),
                    "fixed_N20_penalty_pct": 100.0 * (float(fixed_regret[index]) - 1.0),
                }
            )

        paired_improvement = 100.0 * (fixed_regret - measured_regret)

        def statistic(indices):
            return np.mean(paired_improvement[indices])

        ci_low, ci_high = bootstrap_interval(
            np.arange(len(rows)), statistic, bootstrap_samples, rng
        )
        unique, counts = np.unique(selected_depths, return_counts=True)
        modal_n = int(unique[int(np.argmax(counts))])
        summary_rows.append(
            {
                "resource": resource,
                "resource_label": RESOURCE_LABELS[resource],
                "fixed_control_N": int(nominal_meta["N_best"]),
                "mean_fixed_penalty_pct": 100.0 * (float(np.mean(fixed_regret)) - 1.0),
                "mean_penalty_after_measurement_pct": 100.0 * (float(np.mean(measured_regret)) - 1.0),
                "mean_penalty_reduction_percentage_points": float(np.mean(paired_improvement)),
                "bootstrap_95pct_lower": ci_low,
                "bootstrap_95pct_upper": ci_high,
                "p95_fixed_penalty_pct": 100.0 * (float(np.quantile(fixed_regret, 0.95)) - 1.0),
                "p95_penalty_after_measurement_pct": 100.0
                * (float(np.quantile(measured_regret, 0.95)) - 1.0),
                "p95_penalty_reduction_percentage_points": 100.0
                * (float(np.quantile(fixed_regret, 0.95)) - float(np.quantile(measured_regret, 0.95))),
                "recommendation_changed_fraction": float(
                    np.mean(np.asarray(selected_depths) != int(nominal_meta["N_best"]))
                ),
                "modal_selected_N": modal_n,
                "selected_tau_min_s": float(np.min(selected_taus)),
                "selected_tau_max_s": float(np.max(selected_taus)),
                "bootstrap_samples": int(bootstrap_samples),
            }
        )
    summary_rows.sort(key=lambda row: row["mean_penalty_reduction_percentage_points"], reverse=True)
    return summary_rows, decision_rows


def oat_specs(nominal: dict):
    offsets = np.linspace(-3.0, 3.0, 25)
    return [
        (
            "pulse_fidelity",
            "piPulseFid",
            np.linspace(0.990, 1.0, offsets.size),
        ),
        ("coherence", "T2_scale", np.exp(0.20 * offsets)),
        (
            "coherence",
            "T2_alpha",
            np.clip(nominal["coherence"]["alpha"] + 0.07 * offsets, 0.30, 0.90),
        ),
        ("optical_contrast", "contrast_scale", np.exp(0.18 * offsets)),
        ("photon_rate", "photon_rate_scale", np.exp(0.25 * offsets)),
        ("timing_overhead", "overhead_scale", np.exp(0.20 * offsets)),
    ]


def calibration_for_oat(nominal: dict, measurement: str, value: float) -> dict:
    calibration = deepcopy(nominal)
    calibration["label"] = f"oat_{measurement}_{value:.8g}"
    if measurement == "piPulseFid":
        calibration["pulse"]["piPulseFid"] = float(value)
    elif measurement == "T2_scale":
        calibration["coherence"]["T2_1"] = float(nominal["coherence"]["T2_1"] * value)
    elif measurement == "T2_alpha":
        calibration["coherence"]["alpha"] = float(value)
    elif measurement == "contrast_scale":
        calibration["readout"]["C_1"] = float(nominal["readout"]["C_1"] * value)
    elif measurement == "photon_rate_scale":
        calibration["readout"]["effective_detected_rate_cps"] = float(
            nominal["readout"]["effective_detected_rate_cps"] * value
        )
    elif measurement == "overhead_scale":
        for key in ["t_init", "t_read", "t_dead"]:
            calibration["overheads"][key] = float(nominal["overheads"][key] * value)
    else:
        raise KeyError(measurement)
    return calibration


def run_oat_sweeps(nominal: dict, f_target: float) -> list[dict]:
    rows = []
    for resource, measurement, values in oat_specs(nominal):
        for value in np.unique(values):
            calibration = calibration_for_oat(nominal, measurement, float(value))
            _, meta, _, _, _, _ = sweep.evaluate_calibration(calibration, f_target=f_target)
            window = meta["edt_window_10pct"]
            rows.append(
                {
                    "resource": resource,
                    "resource_label": RESOURCE_LABELS[resource],
                    "measurement": measurement,
                    "measurement_label": MEASUREMENT_LABELS[measurement],
                    "value": float(value),
                    "tau_best_s": float(meta["tau_best"]),
                    "N_best": int(meta["N_best"]),
                    "eta_best": float(meta["eta_best"]),
                    "edt_window_N_min": int(window["N_min"]),
                    "edt_window_N_max": int(window["N_max"]),
                    "edt_window_width_blocks": int(window["N_max"] - window["N_min"]),
                    "edt_window_touches_boundary": int(
                        window["touches_tau_boundary"] or window["touches_N_boundary"]
                    ),
                }
            )
    return rows


def plot_attribution(calibration_rows, oat_rows, nominal, out_png: Path, out_pdf: Path):
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    ordered = sorted(
        calibration_rows,
        key=lambda row: row["mean_penalty_reduction_percentage_points"],
    )
    top = max(calibration_rows, key=lambda row: row["mean_penalty_reduction_percentage_points"])
    top_resource = top["resource"]
    preferred_measurement = {
        "pulse_fidelity": "piPulseFid",
        "coherence": "T2_scale",
        "optical_contrast": "contrast_scale",
        "photon_rate": "photon_rate_scale",
        "timing_overhead": "overhead_scale",
    }[top_resource]
    selected_oat = sorted(
        [row for row in oat_rows if row["measurement"] == preferred_measurement],
        key=lambda row: row["value"],
    )

    fig, (ax_a, ax_b) = plt.subplots(1, 2, figsize=(11.0, 4.3), gridspec_kw={"width_ratios": [1.12, 1.0]})
    fig.suptitle("Which hardware property should be measured first?", fontsize=16, fontweight="bold")

    labels = [row["resource_label"] for row in ordered]
    values = np.array([row["mean_penalty_reduction_percentage_points"] for row in ordered])
    lower = np.array([row["bootstrap_95pct_lower"] for row in ordered])
    upper = np.array([row["bootstrap_95pct_upper"] for row in ordered])
    errors = np.vstack([np.maximum(values - lower, 0.0), np.maximum(upper - values, 0.0)])
    colors = ["#f58518" if row["resource"] == top_resource else "#4c78a8" for row in ordered]
    bars = ax_a.barh(labels, values, xerr=errors, color=colors, alpha=0.92, capsize=3)
    ax_a.axvline(0.0, color="black", linewidth=0.8)
    ax_a.set_xlabel("Reduction in mean penalty vs fixed N=20 (percentage points)")
    ax_a.set_title("Value of measuring one resource")
    ax_a.grid(axis="x", alpha=0.22)
    label_offset = max(float(np.max(np.abs(values))) * 0.025, 0.01)
    for bar, value in zip(bars, values):
        ax_a.text(
            value + label_offset,
            bar.get_y() + bar.get_height() / 2,
            f"{value:.2f}",
            va="center",
            fontsize=8,
        )
    ax_a.text(-0.12, 1.04, "A", transform=ax_a.transAxes, fontsize=14, fontweight="bold")

    x = np.array([row["value"] for row in selected_oat])
    y = np.array([row["N_best"] for row in selected_oat])
    ax_b.step(x, y, where="mid", color="#f58518", linewidth=2.2)
    ax_b.scatter(x, y, color="#f58518", s=24, edgecolor="black", linewidth=0.4, zorder=3)
    boundary_mask = np.array(
        [bool(row["edt_window_touches_boundary"]) for row in selected_oat], dtype=bool
    )
    if np.any(boundary_mask):
        ax_b.scatter(
            x[boundary_mask],
            y[boundary_mask],
            marker="^",
            color="#e45756",
            s=62,
            edgecolor="black",
            linewidth=0.6,
            zorder=4,
            label="Search boundary reached",
        )
    nominal_value = {
        "piPulseFid": nominal["pulse"]["piPulseFid"],
        "T2_scale": 1.0,
        "contrast_scale": 1.0,
        "photon_rate_scale": 1.0,
        "overhead_scale": 1.0,
    }[preferred_measurement]
    ax_b.axvline(nominal_value, color="black", linestyle="--", linewidth=1.1, label="Nominal value")
    ax_b.set_xlabel(MEASUREMENT_LABELS[preferred_measurement])
    ax_b.set_ylabel("Recommended XY8 block count, N")
    ax_b.set_title(f"{RESOURCE_LABELS[top_resource]} changes the selected depth")
    ax_b.grid(alpha=0.22)
    ax_b.legend(frameon=False, loc="upper left")
    ax_b.text(-0.12, 1.04, "B", transform=ax_b.transAxes, fontsize=14, fontweight="bold")

    fig.text(
        0.5,
        0.005,
        "Bars show paired bootstrap 95% intervals; each calibration reveals one resource and leaves all others nominal.",
        ha="center",
        fontsize=8,
    )
    fig.tight_layout(rect=(0, 0.04, 1, 0.94))
    fig.savefig(out_png, dpi=300, bbox_inches="tight")
    fig.savefig(out_pdf, bbox_inches="tight")
    plt.close(fig)


def build_parser():
    parser = argparse.ArgumentParser(description="Attribute XY8 recommendation uncertainty to hardware resources.")
    parser.add_argument("--calibration", default=str(NOMINAL_CALIBRATION))
    parser.add_argument("--samples-csv", default=str(DEFAULT_SAMPLES))
    parser.add_argument("--outdir", default="outputs/reproduced_figures")
    parser.add_argument("--f-target", type=float, default=200e3)
    parser.add_argument("--bootstrap-samples", type=int, default=500)
    parser.add_argument("--permutation-repeats", type=int, default=100)
    parser.add_argument("--seed", type=int, default=DEFAULT_SEED)
    return parser


def main():
    args = build_parser().parse_args()
    outdir = Path(args.outdir)
    outdir.mkdir(parents=True, exist_ok=True)
    nominal = json.loads(Path(args.calibration).read_text(encoding="utf-8"))
    source_rows = load_sample_rows(Path(args.samples_csv))
    rows, surfaces, taus, Ns, nominal_meta, _ = evaluate_existing_samples(
        nominal, source_rows, args.f_target
    )

    correlation_rows = rank_correlations(rows, args.bootstrap_samples, args.seed + 1)
    permutation_rows = permutation_importance(
        rows, args.permutation_repeats, args.seed + 2
    )
    calibration_rows, decision_rows = calibration_value(
        nominal,
        rows,
        surfaces,
        taus,
        Ns,
        nominal_meta,
        args.f_target,
        args.bootstrap_samples,
        args.seed + 3,
    )
    oat_rows = run_oat_sweeps(nominal, args.f_target)

    write_rows(outdir / "xy8_uncertainty_attribution_samples.csv", rows)
    write_rows(outdir / "xy8_uncertainty_rank_correlations.csv", correlation_rows)
    write_rows(outdir / "xy8_uncertainty_permutation_importance.csv", permutation_rows)
    write_rows(outdir / "xy8_calibration_value.csv", calibration_rows)
    write_rows(outdir / "xy8_calibration_value_decisions.csv", decision_rows)
    write_rows(outdir / "xy8_uncertainty_oat_sweeps.csv", oat_rows)
    plot_attribution(
        calibration_rows,
        oat_rows,
        nominal,
        outdir / "fig_xy8_uncertainty_attribution.png",
        outdir / "fig_xy8_uncertainty_attribution.pdf",
    )

    leading = calibration_rows[0]
    summary = {
        "analysis": "XY8 hardware-uncertainty attribution",
        "f_target_Hz": float(args.f_target),
        "sample_count": len(rows),
        "source_samples_csv": str(Path(args.samples_csv)),
        "seed": int(args.seed),
        "bootstrap_samples": int(args.bootstrap_samples),
        "permutation_repeats": int(args.permutation_repeats),
        "nominal_control": {
            "tau_s": float(nominal_meta["tau_best"]),
            "N": int(nominal_meta["N_best"]),
            "total_pi_pulses": 8 * int(nominal_meta["N_best"]),
        },
        "outcomes": list(OUTCOME_LABELS),
        "resource_groups": {key: list(value) for key, value in RESOURCE_GROUPS.items()},
        "rank_correlations": correlation_rows,
        "permutation_importance": permutation_rows,
        "calibration_value": calibration_rows,
        "leading_measurement": {
            "resource": leading["resource"],
            "resource_label": leading["resource_label"],
            "mean_penalty_reduction_percentage_points": leading[
                "mean_penalty_reduction_percentage_points"
            ],
            "bootstrap_95pct": [
                leading["bootstrap_95pct_lower"],
                leading["bootstrap_95pct_upper"],
            ],
        },
        "interpretation_guardrail": (
            "Attribution is conditional on the assumed independent Monte Carlo ranges and the current scalar-fidelity model; "
            "it is not a measured hardware covariance model."
        ),
    }
    if leading["resource"] == "pulse_fidelity":
        summary["presentation_message"] = (
            "Pulse fidelity is the highest-value calibration measurement because revealing it produces the largest "
            "reduction in the expected performance penalty of a fixed control choice."
        )
    else:
        summary["presentation_message"] = (
            f"{leading['resource_label']} is the highest-value calibration measurement under the modeled uncertainty ranges."
        )
    (outdir / "xy8_uncertainty_attribution_summary.json").write_text(
        json.dumps(summary, indent=2), encoding="utf-8"
    )
    print("Wrote XY8 uncertainty-attribution analysis to", outdir)
    print(summary["presentation_message"])


if __name__ == "__main__":
    main()
